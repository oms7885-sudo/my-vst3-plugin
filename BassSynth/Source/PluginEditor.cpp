void PanelLookAndFeel::drawRotarySlider (juce::Graphics& g, int x, int y, int w, int h, float pos,
                                         float startAngle, float endAngle, juce::Slider& s)
{
    const float radius = (float) juce::jmin (w, h) * 0.5f - 3.0f;
    const float cx = (float) x + (float) w * 0.5f, cy = (float) y + (float) h * 0.5f;
    const auto point = [cx, cy] (float angle, float r)
    {
        return juce::Point<float> (cx + r * std::sin (angle), cy - r * std::cos (angle));
    };

    const auto* spec = bsyn::spec::find (s.getComponentID().toRawUTF8());
    const bool stepped = spec != nullptr && spec->kind == bsyn::spec::Kind::Choice;
    const auto choices = stepped && spec->choices != nullptr ? juce::StringArray::fromTokens (spec->choices, "|", "")
                                                            : juce::StringArray {};
    const bool rangeKnob = s.getComponentID().endsWith ("Range");
    const bool waveKnob = s.getComponentID().endsWith ("Wave");
    const bool compact = w < 80;
    const auto& photo = knobPhoto (compact, rangeKnob || waveKnob, s.getComponentID().endsWith ("Freq"));
    const float diameter = juce::jmin (photo.diameter, radius * 1.52f);
    const float skirt = diameter * 0.5f;
    const auto angleAt = [startAngle, endAngle] (float p) { return startAngle + p * (endAngle - startAngle); };

    g.setColour (colour (panelInk));
    g.setFont (panelFont (compact ? 8.5f : 10.5f));
    if ((rangeKnob || waveKnob) && choices.size() > 1)
    {
        for (int i = 0; i < choices.size(); ++i)
        {
            const auto a = angleAt ((float) i / (float) (choices.size() - 1));
            const auto at = point (a, radius + 1.0f);
            if (rangeKnob)
                g.drawText (choices[i], juce::Rectangle<float> (at.x - 8.0f, at.y - 6.0f, 16.0f, 12.0f),
                            juce::Justification::centred);
            else
                drawWaveform (g, at, choices[i]);
        }
    }
    else
    {
        const auto marks = dialMarks (s, spec, compact);
        for (int i = 0; i <= 10; ++i)
        {
            const float p = (float) i / 10.0f;
            if (std::any_of (marks.begin(), marks.end(), [p] (const auto& mark) { return std::abs (p - mark.position) < 0.032f; }))
                continue;
            const auto a = angleAt (p);
            g.drawLine ({ point (a, skirt + 3.0f), point (a, skirt + 5.0f) }, 0.85f);
        }

        for (const auto& mark : marks)
        {
            const auto a = angleAt (mark.position);
            const auto at = point (a, radius + (compact ? 0.0f : 1.0f));
            g.drawLine ({ point (a, skirt + 2.0f), point (a, skirt + (compact ? 4.0f : 6.0f)) }, 1.0f);
            g.drawFittedText (mark.label, juce::Rectangle<float> (at.x - 10.0f, at.y - 5.5f, 20.0f, 11.0f)
                                             .getSmallestIntegerContainer(), juce::Justification::centred, 1, 0.8f);
        }
    }

    const juce::Rectangle<float> body (cx - diameter * 0.5f, cy - diameter * 0.5f, diameter, diameter);
    const auto shadow = body.translated (1.0f, 2.3f);
    g.setColour (juce::Colours::black.withAlpha (0.20f));
    g.fillEllipse (shadow.expanded (0.8f));

    const float angle = startAngle + pos * (endAngle - startAngle);
    const auto& bitmap = photo.image;
    const auto artwork = body.withSizeKeepingCentre (diameter / photo.skirtRatio, diameter / photo.skirtRatio);
    const float scale = artwork.getWidth() / (float) bitmap.getWidth();
    const auto transform = juce::AffineTransform::scale (scale).translated (artwork.getX(), artwork.getY())
                               .rotated (angle - photo.pointerAngle, cx, cy);
    g.setColour (juce::Colours::white);
    {
        juce::Graphics::ScopedSaveState saved (g);
        juce::Path skirt;
        skirt.addEllipse (body);
        g.reduceClipRegion (skirt);
        g.drawImageTransformed (bitmap, transform);
    }

    // The stationary photograph of the metal cap keeps its light direction as the skirt turns.
    {
        juce::Graphics::ScopedSaveState saved (g);
        juce::Path metal;
        metal.addEllipse (body.withSizeKeepingCentre (diameter * photo.capRatio, diameter * photo.capRatio));
        g.reduceClipRegion (metal);
        g.drawImage (bitmap, artwork);
    }

    const auto marker = point (angle, skirt * 0.82f);
    const float markerSize = compact ? 3.7f : 4.8f;
    const juce::Rectangle<float> dot (marker.x - markerSize * 0.5f, marker.y - markerSize * 0.5f,
                                      markerSize, markerSize);
    g.setColour (juce::Colour (0xff171410));
    g.fillEllipse (dot.expanded (0.85f));
    g.setColour (juce::Colour (0xffffeed0));
    g.fillEllipse (dot);
}

void PanelLookAndFeel::drawToggleButton (juce::Graphics& g, juce::ToggleButton& b, bool highlighted, bool)
{
    const auto id = b.getComponentID();
    const bool vertical = id == "noisePink";
    const bool blue = id == "noisePink" || mixerOnSwitch (id);
    const bool silver = id == "comp" || id == "decaySw";
    const bool on = b.getToggleState();
    const auto& sprite = switchPhoto (on, vertical, blue, silver);
    const auto r = b.getLocalBounds().toFloat().withSizeKeepingCentre (vertical ? 19.0f : 51.0f,
                                                                     vertical ? 43.0f : 22.0f);
    const bool flipX = silver && on;
    const bool flipY = vertical && on;
    const float scaleX = r.getWidth() / (float) sprite.getWidth();
    const float scaleY = r.getHeight() / (float) sprite.getHeight();
    const auto transform = juce::AffineTransform::scale (flipX ? -scaleX : scaleX, flipY ? -scaleY : scaleY)
                               .translated (flipX ? r.getRight() : r.getX(), flipY ? r.getBottom() : r.getY());
    g.setColour (juce::Colours::white);
    g.drawImageTransformed (sprite, transform);
    if (highlighted || b.hasKeyboardFocus (false))
    {
        g.setColour (colour (panelInk).withAlpha (0.40f));
        g.drawRect (r.expanded (1.0f), 0.8f);
    }
}

juce::Rectangle<int> PanelLookAndFeel::getTooltipBounds (const juce::String& tipText, juce::Point<int> screenPos,
                                                        juce::Rectangle<int> parentArea)
{
    const auto tl = tipLayout (tipText, 320.0f);
    const int w = (int) std::ceil (tl.getWidth()) + 24, h = (int) std::ceil (tl.getHeight()) + 18;
    return juce::Rectangle<int> (screenPos.x + 14, screenPos.y + 20, w, h).constrainedWithin (parentArea);
}

void PanelLookAndFeel::drawTooltip (juce::Graphics& g, const juce::String& text, int width, int height)
{
    const auto r = juce::Rectangle<float> (0.0f, 0.0f, (float) width, (float) height);
    g.setColour (C::screen);
    g.fillRoundedRectangle (r, 4.0f);
    g.setColour (juce::Colour (0xff5a4a2a));
    g.drawRoundedRectangle (r.reduced (0.5f), 4.0f, 1.0f);
    const auto tl = tipLayout (text, (float) width - 24.0f);
    tl.draw (g, r.reduced (12.0f, 9.0f));
}

juce::Slider::SliderLayout PanelLookAndFeel::getSliderLayout (juce::Slider& slider)
{
    auto layout = juce::LookAndFeel_V4::getSliderLayout (slider);
    const auto valueBox = layout.textBoxBounds;
    layout.textBoxBounds = valueBox.withSizeKeepingCentre (valueBox.getWidth() - 16, valueBox.getHeight() - 2);
    const auto id = slider.getComponentID();
    const bool oscillator = id.startsWith ("osc") && (id.endsWith ("Range") || id.endsWith ("Freq") || id.endsWith ("Wave"));
    const bool loudness = id == "aA" || id == "aD" || id == "aS";
    if (oscillator || loudness)
        layout.textBoxBounds.translate (0, -12);
    return layout;
}

