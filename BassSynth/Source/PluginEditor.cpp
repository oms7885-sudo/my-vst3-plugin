void PanelLookAndFeel::drawRotarySlider (juce::Graphics& g, int x, int y, int w, int h, float pos,
                                         float startAngle, float endAngle, juce::Slider& s)
{
    const float radius = (float) juce::jmin (w, h) * 0.5f - 3.0f;
    const float cx = (float) x + (float) w * 0.5f, cy = (float) y + (float) h * 0.5f;
    const auto point = [cx, cy] (float angle, float r)
    {
        return juce::Point<float> (cx + r * std::sin (angle), cy - r * std::cos (angle));
    };

    const auto* spec = bsyn::spec::find (s.getComponentID().toRawUTF8());
    const bool stepped = spec != nullptr && spec->kind == bsyn::spec::Kind::Choice;
    const auto choices = stepped && spec->choices != nullptr ? juce::StringArray::fromTokens (spec->choices, "|", "")
                                                            : juce::StringArray {};
    const bool rangeKnob = s.getComponentID().endsWith ("Range");
    const bool waveKnob = s.getComponentID().endsWith ("Wave");
    const bool compact = w < 80;
    const auto& photo = knobPhoto (ivory, compact, rangeKnob || waveKnob, s.getComponentID().endsWith ("Freq"));
    const auto& id = s.getComponentID();
    const bool controllerKnob = id == "modAmt" || id == "modMix" || id == "gate" || id == "pickSens";
    const float standardDiameter = juce::jmin (photo.diameter, radius * 1.52f);
    const float diameter = standardDiameter * (controllerKnob ? 0.86f : 1.0f);
    const float tickRadius = standardDiameter * 0.5f;
    const auto angleAt = [startAngle, endAngle] (float p) { return startAngle + p * (endAngle - startAngle); };

    const auto drawTick = [&] (float angle, float distance, float length)
    {
        static const auto tick = decodeImage (mockupDialTick);
        const auto centre = point (angle, distance + length * 0.5f);
        const float width = 2.8f;
        const auto transform = juce::AffineTransform::scale (width / tick.getWidth(), length / tick.getHeight())
                                   .translated (centre.x - width * 0.5f, centre.y - length * 0.5f)
                                   .rotated (angle, centre.x, centre.y);
        g.setColour (ink());
        g.drawImageTransformed (tick, transform, true);
    };
    g.setColour (ink());
    g.setFont (panelFont (compact ? 8.5f : 10.5f));
    if ((rangeKnob || waveKnob) && choices.size() > 1)
    {
        for (int i = 0; i < choices.size(); ++i)
        {
            const auto a = angleAt ((float) i / (float) (choices.size() - 1));
            const auto at = point (a, radius + 1.0f);
            if (rangeKnob)
                g.drawText (choices[i], juce::Rectangle<float> (at.x - 8.0f, at.y - 6.0f, 16.0f, 12.0f),
                            juce::Justification::centred);
            else
                drawWaveform (g, at, choices[i]);
        }
    }
    else
    {
        const auto marks = dialMarks (s, spec, compact);
        const float mainEnd = spec != nullptr ? printedScaleEnd (*spec) : 1.0f;
        for (int i = 0; i <= 10; ++i)
        {
            const float p = mainEnd * (float) i / 10.0f;
            if (std::any_of (marks.begin(), marks.end(), [p] (const auto& mark) { return std::abs (p - mark.position) < 0.032f; }))
                continue;
            const auto a = angleAt (p);
            drawTick (a, tickRadius + 3.0f, 2.5f);
        }

        if (mainEnd < 1.0f)
        {
            for (int i = 1; i <= 3; ++i)
            {
                const auto angle = angleAt (juce::jmap ((float) i / 3.0f, mainEnd, 1.0f));
                g.setColour (C::amber);
                g.drawLine ({ point (angle, tickRadius + 3.0f), point (angle, tickRadius + 9.0f) }, 1.6f);
            }
        }

        for (const auto& mark : marks)
        {
            const auto a = angleAt (mark.position);
            auto at = point (a, radius + (compact ? 0.0f : 1.0f));
            at.y = juce::jmax (at.y, (float) y + 5.5f);
            drawTick (a, tickRadius + 2.0f, compact ? 2.5f : 4.5f);
            g.setColour (ink());
            g.drawFittedText (mark.label, juce::Rectangle<float> (at.x - 10.0f, at.y - 5.5f, 20.0f, 11.0f)
                                             .getSmallestIntegerContainer(), juce::Justification::centred, 1, 0.8f);
        }
    }

    const juce::Rectangle<float> body (cx - diameter * 0.5f, cy - diameter * 0.5f, diameter, diameter);
    const auto shadow = body.translated (1.0f, 2.3f);
    g.setColour (juce::Colours::black.withAlpha (0.20f));
    g.fillEllipse (shadow.expanded (0.8f));

    const float angle = startAngle + pos * (endAngle - startAngle);
    const auto& bitmap = photo.image;
    const auto artwork = body.withSizeKeepingCentre (diameter / photo.skirtRatio, diameter / photo.skirtRatio);
    const float scale = artwork.getWidth() / (float) bitmap.getWidth();
    const auto transform = juce::AffineTransform::scale (scale).translated (artwork.getX(), artwork.getY())
                               .rotated (angle - photo.pointerAngle, cx, cy);
    g.setColour (juce::Colours::white);
    {
        juce::Graphics::ScopedSaveState saved (g);
        juce::Path skirt;
        skirt.addEllipse (body);
        g.reduceClipRegion (skirt);
        g.drawImageTransformed (bitmap, transform);
    }

    // The stationary photograph of the metal cap keeps its light direction as the skirt turns.
    {
        juce::Graphics::ScopedSaveState saved (g);
        juce::Path metal;
        metal.addEllipse (body.withSizeKeepingCentre (diameter * photo.capRatio, diameter * photo.capRatio));
        g.reduceClipRegion (metal);
        g.drawImage (bitmap, artwork);
    }

    const auto marker = point (angle, diameter * 0.41f);
    const float markerSize = compact ? 3.7f : 4.8f;
    const juce::Rectangle<float> dot (marker.x - markerSize * 0.5f, marker.y - markerSize * 0.5f,
                                      markerSize, markerSize);
    g.setColour (juce::Colour (0xff171410));
    g.fillEllipse (dot.expanded (0.85f));
    g.setColour (juce::Colour (0xffffeed0));
    g.fillEllipse (dot);
}

void PanelLookAndFeel::drawToggleButton (juce::Graphics& g, juce::ToggleButton& b, bool highlighted, bool pressed)
{
    const auto id = b.getComponentID();
    const bool vertical = id == "noisePink";
    const bool mixer = mixerOnSwitch (id);
    const bool externalSource = id == "extSrc";
    const bool mode = id == "mode";
    const bool labelledChoice = externalSource || mode;
    const bool blue = mixer || vertical || externalSource;
    const bool compressor = id == "comp";
    const bool silver = compressor || id == "decaySw";
    const bool on = b.getToggleState();
    const auto* rocker = dynamic_cast<const AnimatedRocker*> (&b);
    const float position = rocker != nullptr ? rocker->getPosition() : (on ? 1.0f : 0.0f);

    auto area = b.getLocalBounds().toFloat();
    const auto body = mixer || compressor || labelledChoice ? area.removeFromTop ((float) mixerRockerHeight) : area;
    const auto frame = body.withSizeKeepingCentre (vertical ? 19.0f : (blue || mode ? 54.0f : 51.0f),
                                                   vertical ? 43.0f : 22.0f);
    const auto& sprite = switchPhoto (ivory, position, blue, silver, mode);
    {
        juce::Graphics::ScopedSaveState saved (g);
        if (vertical)
            g.addTransform (juce::AffineTransform::rotation (juce::MathConstants<float>::halfPi)
                                 .translated (frame.getRight(), frame.getY()));
        else
            g.addTransform (juce::AffineTransform::translation (frame.getX(), frame.getY()));

        const juce::Rectangle<float> well (0.0f, 0.0f, vertical ? frame.getHeight() : frame.getWidth(),
                                                             vertical ? frame.getWidth() : frame.getHeight());
        g.setColour (juce::Colours::black.withAlpha (ivory ? 0.22f : 0.42f));
        g.fillPath (softRectangle (well.translated (0.0f, 1.7f).expanded (0.45f), 3.4f));
        g.setColour (juce::Colour (0xff151413));
        g.fillPath (softRectangle (well, 3.0f));
        const auto cap = well.reduced (1.7f, 1.9f);
        // Only the cap tilts. The surrounding recess stays stationary.
        const float tilt = (2.0f * position - 1.0f) * 1.75f;
        const juce::AffineTransform capTilt (1.0f, 0.0f, 0.0f,
                                             tilt / cap.getWidth(), 1.0f, -tilt * 0.5f);
        g.reduceClipRegion (softRectangle (well.reduced (0.7f), 2.5f));
        g.addTransform (capTilt);
        g.reduceClipRegion (softRectangle (cap, 2.0f));
        g.setColour (juce::Colours::white.withAlpha (pressed ? 0.90f : 1.0f));
        g.drawImage (sprite, cap);
        g.setColour (juce::Colours::white.withAlpha (0.18f));
        g.drawHorizontalLine (juce::roundToInt (cap.getY() + 1.0f), cap.getX() + 2.0f, cap.getRight() - 2.0f);
    }

    if (mixer || compressor)
    {
        g.setColour (ink().withAlpha (on || highlighted || b.hasKeyboardFocus (false) ? 1.0f : 0.75f));
        g.setFont (panelFont (13.0f));
        g.drawText (on ? "ON" : "OFF", area.withTrimmedRight (2.0f),
                    mixer ? juce::Justification::centredRight : juce::Justification::centred);
        return;
    }

    if (labelledChoice)
    {
        const auto* spec = bsyn::spec::find (id.toRawUTF8());
        const auto choices = juce::StringArray::fromTokens (utf8 (spec->choices), "|", "");
        g.setFont (panelFont (11.0f));
        if (externalSource)
            area.removeFromLeft (10.0f);
        const auto left = area.removeFromLeft (mode ? area.getWidth() * 0.5f : 26.0f);
        g.setColour (on ? ink().withAlpha (0.54f) : ink());
        g.drawText (choices[0].toUpperCase(), left, juce::Justification::centred);
        g.setColour (on ? ink() : ink().withAlpha (0.54f));
        g.drawText (choices[1].toUpperCase(), area, juce::Justification::centred);
    }
    else if (vertical)
    {
        g.setFont (panelFont (11.0f));
        g.setColour (on ? ink().withAlpha (0.54f) : ink());
        g.drawText ("WHITE", area.withBottom (frame.getY() - 1.0f), juce::Justification::centred);
        g.setColour (on ? ink() : ink().withAlpha (0.54f));
        g.drawText ("PINK", area.withY (frame.getBottom() + 1.0f).withBottom (body.getBottom()),
                    juce::Justification::centred);
    }
    else if (id == "decaySw")
    {
        const juce::Rectangle<float> indicator (frame.getRight() + 5.0f, frame.getCentreY() - 2.5f, 5.0f, 5.0f);
        g.setColour (on ? C::amber : C::pilotOff);
        g.fillEllipse (indicator);
    }

    if (highlighted || b.hasKeyboardFocus (false))
    {
        g.setColour (ink().withAlpha (0.40f));
        g.drawRect (frame.expanded (1.0f), 0.8f);
    }
}

