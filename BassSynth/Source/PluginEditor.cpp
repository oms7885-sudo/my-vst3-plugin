void PanelLookAndFeel::drawRotarySlider (juce::Graphics& g, int x, int y, int w, int h, float pos,
                                         float startAngle, float endAngle, juce::Slider& s)
{
    const auto& finish = themes[theme];
    const float radius = (float) juce::jmin (w, h) * 0.5f - 3.0f;
    const float cx = (float) x + (float) w * 0.5f, cy = (float) y + (float) h * 0.5f;
    const auto point = [cx, cy] (float angle, float r)
    {
        return juce::Point<float> (cx + r * std::sin (angle), cy - r * std::cos (angle));
    };

    const auto* spec = bsyn::spec::find (s.getComponentID().toRawUTF8());
    const bool stepped = spec != nullptr && spec->kind == bsyn::spec::Kind::Choice;
    const int steps = stepped ? juce::jmax (1, (int) (spec->max - spec->min)) : 10;
    const auto choices = stepped && spec->choices != nullptr ? juce::StringArray::fromTokens (spec->choices, "|", "")
                                                            : juce::StringArray {};
    const bool rangeKnob = s.getComponentID().endsWith ("Range");
    const bool waveKnob = s.getComponentID().endsWith ("Wave");
    g.setColour (colour (finish.ink));
    for (int i = 0; i <= steps; ++i)
    {
        const float a = startAngle + (float) i / (float) steps * (endAngle - startAngle);
        const bool major = stepped || i % 5 == 0;
        if (rangeKnob && i < choices.size())
        {
            const auto at = point (a, radius - 4.0f);
            g.setFont (panelFont (10.0f));
            g.drawText (choices[i], juce::Rectangle<float> (at.x - 8.0f, at.y - 6.0f, 16.0f, 12.0f),
                        juce::Justification::centred);
        }
        else if (waveKnob && i < choices.size())
            drawWaveform (g, point (a, radius - 1.0f), choices[i]);
        else
            g.drawLine ({ point (a, radius * (major ? 0.86f : 0.90f)), point (a, radius * 0.99f) },
                        major ? 1.4f : 0.8f);
    }

    const float rim = radius * ((rangeKnob || waveKnob) ? 0.76f : 0.82f);
    const juce::Rectangle<float> skirt (cx - rim, cy - rim, 2.0f * rim, 2.0f * rim);
    for (int i = 4; i > 0; --i)
    {
        g.setColour (juce::Colours::black.withAlpha (0.12f));
        g.fillEllipse (skirt.translated (1.7f, 3.8f).expanded ((float) i * 0.85f));
    }
    g.setGradientFill (juce::ColourGradient (juce::Colour (0xff52504d), cx - rim * 0.35f, cy - rim,
                                             juce::Colour (0xff080807), cx + rim * 0.5f, cy + rim, false));
    g.fillEllipse (skirt);
    g.setColour (juce::Colours::black.withAlpha (0.62f));
    g.drawEllipse (skirt, 0.9f);

    for (int i = 0; i < 44; ++i)
    {
        const float a = juce::MathConstants<float>::twoPi * (float) i / 44.0f;
        g.setColour (juce::Colours::black.withAlpha (0.23f));
        g.drawLine ({ point (a, rim * 0.72f), point (a, rim * 0.98f) }, 0.85f);
    }

    const float cap = rim * 0.67f;
    const juce::Rectangle<float> disc (cx - cap, cy - cap, 2.0f * cap, 2.0f * cap);
    g.setColour (colour (finish.cap).darker (0.46f));
    g.fillEllipse (disc.expanded (1.2f));
    {
        juce::Graphics::ScopedSaveState saved (g);
        juce::Path mask;
        mask.addEllipse (disc);
        g.reduceClipRegion (mask);
        g.setColour (juce::Colours::white);
        g.drawImage (finishes (theme).cap, disc);
    }
    g.setColour (juce::Colours::white.withAlpha (0.18f));
    g.drawEllipse (disc.reduced (0.45f), 0.85f);

    const float angle = startAngle + pos * (endAngle - startAngle);
    g.setColour (s.isMouseOverOrDragging() ? C::amber : juce::Colours::whitesmoke);
    g.drawLine ({ point (angle, cap * 0.95f), point (angle, rim * 0.98f) }, 2.2f);
}

void PanelLookAndFeel::drawToggleButton (juce::Graphics& g, juce::ToggleButton& b, bool highlighted, bool)
{
    const auto& finish = themes[theme];
    const auto* spec = bsyn::spec::find (b.getComponentID().toRawUTF8());
    const bool mixer = spec != nullptr && juce::String (spec->section) == "Mixer";
    const bool on = b.getToggleState();
    const bool vertical = b.getComponentID() == "osc3Ctl" || b.getComponentID() == "noisePink";
    const auto r = b.getLocalBounds().toFloat().withSizeKeepingCentre (vertical ? 17.0f : 48.0f,
                                                                     vertical ? 36.0f : 19.0f);
    g.setColour (juce::Colours::black.withAlpha (0.40f));
    g.fillRoundedRectangle (r.expanded (2.0f).translated (0.0f, 1.0f), 1.4f);
    g.setColour (juce::Colour (0xff171615));
    g.fillRoundedRectangle (r.expanded (0.9f), 1.0f);
    const auto face = colour (mixer ? finish.mixer : finish.switchColour).darker (on ? 0.0f : 0.12f);
    auto paddle = r.reduced (1.6f);
    g.setGradientFill (juce::ColourGradient (face.brighter (highlighted ? 0.36f : 0.16f),
                                             paddle.getX(), paddle.getY(), face.darker (0.17f),
                                             paddle.getRight(), paddle.getBottom(), false));
    g.fillRect (paddle);
    g.setColour (juce::Colours::black.withAlpha (0.28f));
    if (vertical)
        g.fillRect (on ? paddle.removeFromBottom (10.0f) : paddle.removeFromTop (10.0f));
    else
        g.fillRect (on ? paddle.removeFromLeft (12.0f) : paddle.removeFromRight (12.0f));

}

