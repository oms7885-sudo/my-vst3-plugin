    juce::Image fadeEdge (const char* photo, bool acrossX)
    {
        auto edge = decodeImage (photo).convertedToFormat (juce::Image::ARGB);
        juce::Image::BitmapData pixels (edge, juce::Image::BitmapData::readWrite);
        const int end = (acrossX ? pixels.width : pixels.height) - 1;
        for (int y = 0; y < pixels.height; ++y)
            for (int x = 0; x < pixels.width; ++x)
            {
                const int at = acrossX ? x : y;
                const float alpha = juce::jlimit (0.0f, 1.0f, (float) juce::jmin (at, end - at) / 2.5f);
                pixels.setPixelColour (x, y, pixels.getPixelColour (x, y).withAlpha (alpha));
            }
        return edge;
    }

    void drawMainBezel (juce::Graphics& g, juce::Rectangle<int> bounds)
    {
        static const auto top = fadeEdge (topEdge, false);
        static const auto bottom = fadeEdge (bottomEdge, false);
        static const auto left = fadeEdge (leftEdge, true);
        static const auto right = fadeEdge (rightEdge, true);
        auto area = bounds.toFloat();
        g.setColour (juce::Colours::white);
        g.drawImage (left, area.removeFromLeft (15.0f));
        g.drawImage (right, area.removeFromRight (15.0f));
        g.drawImage (top, area.removeFromTop (14.0f).expanded (4.0f, 0.0f).translated (0.0f, -5.0f));
        g.drawImage (bottom, area.removeFromBottom (15.0f).expanded (4.0f, 0.0f));
    }

