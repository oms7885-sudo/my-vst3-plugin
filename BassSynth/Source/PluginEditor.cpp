BassSynthEditor::BassSynthEditor (BassSynthProcessor& p)
    : AudioProcessorEditor (&p), proc (p)
{
    setLookAndFeel (&lnf);

    int auxiliaryCount = 0;
    for (const auto& parameter : bsyn::spec::params)
    {
        const bool small = findPlacement (parameter.id) == nullptr;
        auxiliaryCount += small ? 1 : 0;
        addControl (parameter, small);
    }

    for (int i = 0; i < proc.getNumPrograms(); ++i)
        presetBox.addItem (proc.getProgramName (i), i + 1);
    presetBox.setSelectedId (proc.getCurrentProgram() + 1, juce::dontSendNotification);
    presetBox.onChange = [this] { proc.setCurrentProgram (presetBox.getSelectedId() - 1); };
    addAndMakeVisible (presetBox);

    presetBox.setTitle ("Preset");
    const int extraRows = juce::jmax (0, (auxiliaryCount - 1) / auxiliaryColumns);
    setSize (editorW, editorH + extraRows * auxiliaryRowHeight);
    startTimerHz (30);
}

BassSynthEditor::~BassSynthEditor()
{
    stopTimer();
    setLookAndFeel (nullptr);
}

void BassSynthEditor::addControl (const bsyn::spec::Param& d, bool small)
{
    Control k;
    k.id = d.id; k.label = utf8 (d.label); k.small = small;
    if (k.id == "noisePink") k.label = "White / Pink";
    if (k.id == "osc3Ctl") k.label = "Osc. 3 Control";
    if (d.kind == bsyn::spec::Kind::Bool)
    {
        k.button = std::make_unique<juce::ToggleButton>();
        k.button->setComponentID (d.id);
        k.button->setTitle (utf8 (d.name));
        k.button->setTooltip (tipFor (d.id));
        k.buttonAttachment = std::make_unique<juce::AudioProcessorValueTreeState::ButtonAttachment> (proc.apvts, d.id, *k.button);
        addAndMakeVisible (*k.button);
    }
    else
    {
        k.slider = std::make_unique<juce::Slider> (juce::Slider::RotaryVerticalDrag, juce::Slider::TextBoxBelow);
        k.slider->setComponentID (d.id);
        k.slider->setTitle (utf8 (d.name));
        const auto pi = juce::MathConstants<float>::pi;
        if (d.kind == bsyn::spec::Kind::Choice && (k.id.endsWith ("Range") || k.id.endsWith ("Wave")))
        {
            const bool withoutLo = k.id.endsWith ("Range") && d.choices != nullptr
                                && ! juce::String (d.choices).startsWith ("LO|");
            k.slider->setRotaryParameters (pi * (withoutLo ? 1.7f : 1.5f), pi * 2.5f, true);
        }
        else
            k.slider->setRotaryParameters (pi * 1.25f, pi * 2.75f, true);
        k.slider->setTextBoxStyle (juce::Slider::TextBoxBelow, false, small ? 74 : 84, 15);
        k.slider->setMouseDragSensitivity (small ? 160 : 200);
        // hold Ctrl (Cmd on Mac) while dragging for fine adjustment (detuning Frequency by cents)
        k.slider->setVelocityModeParameters (0.4, 1, 0.02, true, juce::ModifierKeys::ctrlAltCommandModifiers);
        k.sliderAttachment = std::make_unique<juce::AudioProcessorValueTreeState::SliderAttachment> (proc.apvts, d.id, *k.slider);
        if (auto* prm = proc.apvts.getParameter (d.id))
            k.slider->setDoubleClickReturnValue (true, (double) prm->convertFrom0to1 (prm->getDefaultValue()));
        k.slider->setTooltip (tipFor (d.id));
        addAndMakeVisible (*k.slider);
    }
    controls.push_back (std::move (k));
}

void BassSynthEditor::resized()
{
    panelArea = { cheekW, panelTop, getWidth() - 2 * cheekW, panelHeight };
    displayArea = mainPanelBounds ({ (controllerLeftX + controllerRightX - 174) / 2, 104, 174, 130 });
    overloadArea = mainPanelBounds ({ 786, 97, 100, 44 });
    const int setupTop = panelArea.getBottom() + setupGap;
    setupArea = { panelX (47), setupTop, panelX (1107) - panelX (47), getHeight() - setupTop - 11 };
    badgeArea = { panelX (1140), setupTop + 15, 202, 78 };
    presetBox.setBounds (96, 10, 215, 25);

    const auto place = [] (Control& k, int x, int y, bool compact)
    {
        const int labelWidth = compact ? 94 : 98;
        k.labelArea = { x - labelWidth / 2, y, labelWidth, 18 };
        if (k.id == "osc2Freq" || k.id == "osc3Freq")
            k.labelArea.translate (0, 3);
        if (k.slider)
        {
            const int width = compact ? 74 : 98;
            const bool filterEnvelope = k.id == "fA" || k.id == "fD" || k.id == "fS";
            const int height = compact ? 80 : (filterEnvelope ? 86 : 104);
            k.slider->setBounds (x - width / 2, y + 17, width, height);
            return;
        }

        if (bridgesDivider (k.id))
            k.labelArea = { x - 80, y - 2, 74, 23 };
        else if (mixerOnSwitch (k.id))
            k.labelArea = { x - 24, y + 38, 48, 15 };

        if (k.id == "noisePink")
            k.button->setBounds (x - 13, y + 17, 26, 45);
        else
            k.button->setBounds (x - 27, y + (mixerOnSwitch (k.id) ? 16 : 19), 54, 28);
    };

    const int step = setupArea.getWidth() / auxiliaryColumns;
    int auxiliaryIndex = 0;
    for (auto& k : controls)
    {
        if (const auto* slot = findPlacement (k.id))
            place (k, panelX (slot->x), slot->y - panelTopTrim, false);
        else
        {
            const int row = auxiliaryIndex / auxiliaryColumns;
            const int column = auxiliaryIndex % auxiliaryColumns;
            place (k, setupArea.getX() + step / 2 + column * step,
                   setupArea.getY() + 10 + row * auxiliaryRowHeight, true);
            ++auxiliaryIndex;
        }
    }
}

void BassSynthEditor::paint (juce::Graphics& g)
{
    const auto ink = colour (panelInk);
    const auto rule = colour (panelRule);
    const auto& textures = finishes();
    auto rail = getLocalBounds();
    const auto left = rail.removeFromLeft (cheekW), right = rail.removeFromRight (cheekW);
    g.setColour (juce::Colours::white);
    g.drawImage (textures.leftWood, left.toFloat());
    g.drawImage (textures.rightWood, right.toFloat());
    g.drawImage (textures.header, rail.removeFromTop (panelArea.getY()).toFloat());
    drawLowerWood (g, rail.withY (panelArea.getBottom()).withBottom (getHeight()), textures.lowerWood);

    drawSurface (g, panelArea);
    drawMainBezel (g, panelArea);

    g.setColour (rule);
    for (const int x : { controllerDivider, oscillatorDivider, modifierDivider, outputDivider })
        g.drawVerticalLine (panelX (x), (float) panelArea.getY() + 5.0f, (float) panelArea.getBottom() - 9.0f);
    g.drawHorizontalLine (envelopeDivider - panelTopTrim, (float) panelX (modifierDivider), (float) panelX (outputDivider));

    g.setColour (colour (0xff322c26));
    g.setFont (panelFont (11.0f));
    g.drawText ("PRESET", juce::Rectangle<int> { 44, 10, 49, 25 }, juce::Justification::centredLeft);

    struct Caption { const char* text; juce::Rectangle<int> area; };
    const Caption captions[] {
        { "CONTROLLERS", { 26, 481, 222, 33 } }, { "OSCILLATOR BANK", { 248, 481, 346, 33 } },
        { "MIXER", { 594, 481, 330, 33 } }, { "FILTER CONTOUR", { 924, 66, 334, 22 } },
        { "LOUDNESS CONTOUR", { 924, 322, 334, 26 } }, { "OUTPUT", { 1258, 481, 112, 33 } }
    };
    g.setColour (ink);
    g.setFont (panelFont (28.0f));
    for (const auto& caption : captions)
        g.drawFittedText (caption.text, mainPanelBounds (caption.area).reduced (4, 0), juce::Justification::centred, 1);
    g.setFont (panelFont (17.0f));
    for (int i = 0; i < 3; ++i)
        g.drawText ("OSCILLATOR " + juce::String (i + 1),
                    mainPanelBounds ({ oscillatorFrequencyX - 100, oscillatorRow (i) - 16, 200, 19 }),
                    juce::Justification::centred);

    {
        juce::Graphics::ScopedSaveState saved (g);
        juce::Path inset;
        inset.addRoundedRectangle (setupArea.toFloat(), 4.0f);
        g.reduceClipRegion (inset);
        drawSurface (g, setupArea);
        g.setColour (juce::Colours::black.withAlpha (0.10f));
        g.fillRect (setupArea);
        static const auto insetLip = fadeEdge (insetEdge, false);
        g.setColour (juce::Colours::white);
        g.drawImage (insetLip, setupArea.toFloat().withHeight (8.0f));
    }
    g.setColour (rule);
    g.drawRoundedRectangle (setupArea.toFloat(), 4.0f, 1.0f);
    drawScrew (g, (float) setupArea.getX() + 7.0f, (float) setupArea.getY() + 9.0f);
    drawScrew (g, (float) setupArea.getRight() - 7.0f, (float) setupArea.getBottom() - 7.0f);

    g.setColour (colour (badgeColour));
    g.fillRoundedRectangle (badgeArea.toFloat(), 5.0f);
    g.setColour (juce::Colours::black.withAlpha (0.4f));
    g.drawRoundedRectangle (badgeArea.toFloat(), 5.0f, 1.0f);
    drawScrew (g, (float) badgeArea.getX() + 10.0f, (float) badgeArea.getCentreY());
    drawScrew (g, (float) badgeArea.getRight() - 10.0f, (float) badgeArea.getCentreY());
    g.setColour (ink);
    drawWordmark (g, badgeArea.withTrimmedTop (8));
    g.setFont (panelFont (10.0f, true, 0.19f));
    g.drawText ("DI TO SYNTH", badgeArea.withTrimmedTop (53).withHeight (14), juce::Justification::centred);

    for (const auto& k : controls)
    {
        g.setColour (ink);
        const float labelSize = k.small || k.button != nullptr ? 13.0f : 16.0f;
        g.setFont (panelFont (labelSize));
        g.drawFittedText (k.label.toUpperCase(), k.labelArea, juce::Justification::centred, 2, 0.78f);
    }

    const auto led = [&g] (int x, int y, bool on)
    {
        const juce::Rectangle<float> lens ((float) x - 4.0f, (float) y - 4.0f, 8.0f, 8.0f);
        g.setColour (juce::Colour (0xff17110e));
        g.fillEllipse (lens.expanded (2.0f));
        if (on)
        {
            g.setColour (C::amber.withAlpha (0.26f));
            g.fillEllipse (lens.expanded (3.0f));
        }
        g.setColour (on ? C::amber : C::pilotOff);
        g.fillEllipse (lens);
    };
    g.setColour (C::screen);
    g.fillRoundedRectangle (displayArea.toFloat(), 4.0f);
    g.setColour (rule);
    g.drawRoundedRectangle (displayArea.toFloat(), 4.0f, 1.0f);
    const int displayX = displayArea.getX(), displayY = displayArea.getY();
    led (displayX + 17, displayY + 18, trigFlash > 0);
    led (displayX + 93, displayY + 18, gateLed);
    led (overloadArea.getCentreX(), overloadArea.getY() + 11, overloadHold > 0);
    g.setFont (panelFont (9.0f));
    g.setColour (ink);
    g.drawText ("OVERLOAD", overloadArea.withTrimmedTop (19).withHeight (15), juce::Justification::centred);
    g.setColour (C::silk);
    g.drawText ("TRIG", juce::Rectangle<int> { displayX + 28, displayY + 10, 40, 16 }, juce::Justification::centredLeft);
    g.drawText ("GATE", juce::Rectangle<int> { displayX + 104, displayY + 10, 50, 16 }, juce::Justification::centredLeft);

    juce::String note = "--";
    if (freq > 0.0f)
    {
        static const char* names[] { "C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B" };
        const int midi = (int) std::lround (69.0 + 12.0 * std::log2 (freq / 440.0));
        note = juce::String (names[((midi % 12) + 12) % 12]) + juce::String (midi / 12 - 1)
             + "   " + juce::String (freq, 1) + " Hz";
    }
    g.setColour (C::amber);
    g.setFont (monoFont (16.0f));
    g.drawText (note, juce::Rectangle<int> { displayX + 11, displayY + 35, 146, 26 }, juce::Justification::centred);
    const auto meter = [&] (const char* label, int y, float value)
    {
        g.setFont (panelFont (8.5f));
        g.setColour (C::silk);
        g.drawText (label, juce::Rectangle<int> { displayX + 10, displayY + y, 40, 13 }, juce::Justification::centredLeft);
        g.setColour (juce::Colour (0xff4a3b25));
        g.fillRect (displayX + 52, displayY + y + 5, 101, 3);
        g.setColour (C::amber);
        g.fillRect (displayX + 52, displayY + y + 5, juce::roundToInt (101.0f * juce::jlimit (0.0f, 1.0f, value)), 3);
    };
    meter ("INPUT", 65, input);
    meter ("FILTER", 84, filterEnv);
    meter ("AMP", 103, ampEnv);
}

void BassSynthEditor::timerCallback()
{
    const uint32_t t = proc.displayTrig.load();
    if (t != lastTrig) { lastTrig = t; trigFlash = 3; }
    else if (trigFlash > 0) --trigFlash;
    gateLed = proc.displayGate.load();
    freq = proc.displayFreq.load();
    input = proc.displayInput.load();
    filterEnv = proc.displayFilterEnv.load();
    ampEnv = proc.displayAmpEnv.load();
    const bool wasOverloaded = overloadHold > 0;
    if (input > 0.9f) overloadHold = 8; else if (overloadHold > 0) --overloadHold;
    if (wasOverloaded != (overloadHold > 0)) repaint (overloadArea);
    repaint (displayArea);
}

