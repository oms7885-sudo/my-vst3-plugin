    struct DialMark { float position; juce::String label; };

    float printedScaleEnd (const bsyn::spec::Param& spec)
    {
        return spec.dialBreak != 0.0f && spec.dialBreak > spec.dial0 && spec.dialBreak < spec.dial1
             ? (spec.dialBreak - spec.dial0) / (spec.dial1 - spec.dial0)
             : 1.0f;
    }

    juce::String dialNumber (double value)
    {
        if (std::abs (value) >= 1000.0)
            return juce::String (value / 1000.0, std::fmod (value, 1000.0) == 0.0 ? 0 : 1) + "k";
        return juce::String (value, std::fmod (value, 1.0) == 0.0 ? 0 : 1);
    }

    std::vector<DialMark> dialMarks (juce::Slider& dial, const bsyn::spec::Param* spec, bool compact)
    {
        const auto min = dial.getMinimum(), max = dial.getMaximum();
        const auto unit = spec != nullptr ? juce::String (spec->unit) : juce::String();
        if (spec != nullptr && spec->dial0 != spec->dial1)
        {
            const bool signedScale = spec->dial0 < 0.0f && spec->dial1 > 0.0f;
            const int steps = compact ? 2 : (signedScale ? 10 : 5);
            std::vector<DialMark> marks;
            const float end = printedScaleEnd (*spec);
            for (int i = 0; i <= steps; ++i)
            {
                const float position = (float) i / (float) steps;
                const auto number = juce::jmap (position, spec->dial0, end < 1.0f ? spec->dialBreak : spec->dial1);
                const auto sign = number < 0.0f ? juce::String::charToString (0x2212)
                                               : (signedScale && number > 0.0f ? juce::String ("+") : juce::String());
                marks.push_back ({ position * end, sign + dialNumber (std::abs (number)) });
            }
            return marks;
        }

        if (spec != nullptr && spec->timeDial)
        {
            const DialMark times[] {
                { 10.0f, "10ms" }, { 200.0f, "200" }, { 600.0f, "600" },
                { 1000.0f, "1s" }, { 5000.0f, "5s" }, { 10000.0f, "10s" }
            };
            std::vector<DialMark> marks;
            for (const auto& time : times)
                if (time.position >= min && time.position <= max)
                    marks.push_back ({ (float) dial.valueToProportionOfLength (time.position), time.label });
            return marks;
        }

        std::vector<double> candidates;
        if (unit == "Hz")
            candidates = { 60, 100, 200, 500, 1000, 2000 };
        else if (unit == "ms")
            candidates = { 2, 5, 10, 20, 50, 100, 200, 500, 1000, 2000 };
        else if (unit == "st")
            candidates = { -6, -3, 0, 3, 6 };
        else if (unit == "dB")
            candidates = { -60, -48, -36, -24, -12, 0, 6 };
        else if (max > min)
        {
            const auto step = (max - min) / (compact ? 2.0 : 3.0);
            for (int i = 1; i < (compact ? 2 : 3); ++i)
                candidates.push_back (min + i * step);
        }

        std::vector<DialMark> marks { { 0.0f, dialNumber (min) } };
        const float spacing = compact ? 0.25f : 0.135f;
        for (const auto value : candidates)
        {
            if (value <= min || value >= max)
                continue;
            const auto pos = (float) dial.valueToProportionOfLength (value);
            if (pos - marks.back().position >= spacing && 1.0f - pos >= spacing)
                marks.push_back ({ pos, dialNumber (value) });
        }
        marks.push_back ({ 1.0f, dialNumber (max) });
        return marks;
    }

    void drawWaveform (juce::Graphics& g, juce::Point<float> origin, const juce::String& waveform)
    {
        juce::Path icon;
        const auto start = [&] (float x, float y) { icon.startNewSubPath (origin.x + x, origin.y + y); };
        const auto to = [&] (float x, float y) { icon.lineTo (origin.x + x, origin.y + y); };
        if (waveform == "Triangle" || waveform == "Tri-Saw")
        {
            start (-4.0f, 2.5f); to (waveform == "Triangle" ? 0.0f : 2.0f, -2.5f); to (4.0f, 2.5f);
        }
        else if (waveform == "Saw" || waveform == "Rev Saw")
        {
            const float direction = waveform == "Saw" ? 1.0f : -1.0f;
            start (-4.0f * direction, 2.5f); to (3.0f * direction, -2.5f); to (3.0f * direction, 2.5f);
        }
        else
        {
            const float edge = waveform == "Wide Pulse" ? 2.0f : (waveform == "Narrow Pulse" ? -1.0f : 0.5f);
            start (-4.0f, 2.5f); to (-3.0f, 2.5f); to (-3.0f, -2.5f); to (edge, -2.5f);
            to (edge, 2.5f); to (4.0f, 2.5f);
        }
        g.strokePath (icon, juce::PathStrokeType (1.1f));
    }

