BassSynthEditor::BassSynthEditor (BassSynthProcessor& p)
    : AudioProcessorEditor (&p), proc (p)
{
    lnf.setIvory (themeSettings().getBoolValue ("ivoryTheme", false));
    setLookAndFeel (&lnf);

    int auxiliaryCount = 0;
    for (const auto& parameter : bsyn::spec::params)
    {
        const bool small = findPlacement (parameter.id) == nullptr;
        auxiliaryCount += small ? 1 : 0;
        addControl (parameter, small);
    }

    for (int i = 0; i < proc.getNumPrograms(); ++i)
        presetBox.addItem (proc.getProgramName (i), i + 1);
    presetBox.setSelectedId (proc.getCurrentProgram() + 1, juce::dontSendNotification);
    presetBox.onChange = [this] { proc.setCurrentProgram (presetBox.getSelectedId() - 1); };
    addAndMakeVisible (panel);
    panel.addAndMakeVisible (presetBox);

    presetBox.setTitle ("Preset");
    savePresetButton.setTooltip ("Save the current settings as a user preset");
    loadPresetButton.setTooltip ("Load a saved user preset");
    savePresetButton.onClick = [this] { choosePresetFile (true); };
    loadPresetButton.onClick = [this] { choosePresetFile (false); };
    themeButton.setTitle ("Theme");
    themeButton.onClick = [this] { setIvoryTheme (! lnf.isIvory()); };
    themeButton.setTooltip ("Switch between Basic and Ivory");
    for (auto* button : { &savePresetButton, &loadPresetButton, &themeButton })
    {
        button->setColour (juce::TextButton::buttonColourId, lnf.findColour (juce::ComboBox::backgroundColourId));
        button->setColour (juce::TextButton::textColourOffId, C::silk);
        panel.addAndMakeVisible (*button);
    }
    const int extraRows = juce::jmax (0, (auxiliaryCount - 1) / auxiliaryColumns);
    const int designHeight = editorH + extraRows * auxiliaryRowHeight;
    panel.setSize (editorW, designHeight);
    layoutPanel();
    setSize (editorW, designHeight);
    setResizeLimits (editorW * 3 / 5, designHeight * 3 / 5, editorW * 3 / 2, designHeight * 3 / 2);
    getConstrainer()->setFixedAspectRatio ((double) editorW / designHeight);
    setResizable (true, true);
    startTimerHz (30);
}

