    juce::Path softRectangle (juce::Rectangle<float> area, float radius)
    {
        const auto x = area.getX(), y = area.getY(), right = area.getRight(), bottom = area.getBottom();
        const float r = juce::jmin (radius, area.getWidth() * 0.5f, area.getHeight() * 0.5f);
        const float control = r * 0.72f;
        juce::Path shape;
        shape.startNewSubPath (x + r, y);
        shape.lineTo (right - r, y);
        shape.cubicTo (right - r + control, y, right, y + r - control, right, y + r);
        shape.lineTo (right, bottom - r);
        shape.cubicTo (right, bottom - r + control, right - r + control, bottom, right - r, bottom);
        shape.lineTo (x + r, bottom);
        shape.cubicTo (x + r - control, bottom, x, bottom - r + control, x, bottom - r);
        shape.lineTo (x, y + r);
        shape.cubicTo (x, y + r - control, x + r - control, y, x + r, y);
        shape.closeSubPath();
        return shape;
    }

