    juce::Image decodeImage (const char* data)
    {
        juce::MemoryOutputStream bytes;
        if (! juce::Base64::convertFromBase64 (bytes, data))
            return {};
        return juce::ImageFileFormat::loadFrom (bytes.getData(), bytes.getDataSize());
    }

