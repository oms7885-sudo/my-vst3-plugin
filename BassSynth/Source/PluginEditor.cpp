void BassSynthEditor::choosePresetFile (bool save)
{
    if (presetFileChooser != nullptr)
        return;

    const auto folder = juce::File::getSpecialLocation (juce::File::userDocumentsDirectory)
                            .getChildFile ("mOog").getChildFile ("Presets");
    if (const auto result = folder.createDirectory(); result.failed())
    {
        juce::AlertWindow::showMessageBoxAsync (juce::MessageBoxIconType::WarningIcon, "User presets",
                                               "Could not open the preset folder. " + result.getErrorMessage(), {}, this);
        return;
    }

    const auto initialFile = save ? folder.getChildFile ("My Preset.preset") : folder;
    presetFileChooser = std::make_unique<juce::FileChooser> (save ? "Save user preset" : "Load user preset",
                                                            initialFile, "*.preset", true, false, this);
    const int flags = juce::FileBrowserComponent::canSelectFiles
                    | (save ? juce::FileBrowserComponent::saveMode | juce::FileBrowserComponent::warnAboutOverwriting
                            : juce::FileBrowserComponent::openMode);
    const juce::Component::SafePointer<BassSynthEditor> safe (this);
    presetFileChooser->launchAsync (flags, [safe, save, folder] (const juce::FileChooser& chooser)
    {
        if (safe == nullptr)
            return;

        const auto file = chooser.getResult();
        safe->presetFileChooser.reset();
        if (file == juce::File {})
            return;

        if (save && file.getParentDirectory() != folder)
        {
            juce::AlertWindow::showMessageBoxAsync (juce::MessageBoxIconType::WarningIcon, "Save user preset",
                                                   "Choose a file in " + folder.getFullPathName(), {}, safe.getComponent());
            return;
        }

        safe->handlePresetFile (file, save);
    });
}

void BassSynthEditor::handlePresetFile (const juce::File& file, bool save)
{
    const auto showError = [this, save] (const juce::String& message)
    {
        juce::AlertWindow::showMessageBoxAsync (juce::MessageBoxIconType::WarningIcon,
                                               save ? "Save user preset" : "Load user preset", message, {}, this);
    };

    if (! file.hasFileExtension (".preset"))
    {
        showError ("Choose a file with the .preset extension.");
        return;
    }

    juce::MemoryBlock state;
    if (save)
    {
        proc.getStateInformation (state);
        if (state.isEmpty() || ! file.replaceWithData (state.getData(), state.getSize()))
        {
            showError ("Could not save the preset.");
            return;
        }
    }
    else
    {
        constexpr int maxPresetSize = 1024 * 1024;
        juce::FileInputStream stream (file);
        if (! stream.openedOk() || stream.readIntoMemoryBlock (state, maxPresetSize + 1) > maxPresetSize)
        {
            showError ("Could not read the preset.");
            return;
        }

        const auto size = (int) state.getSize();
        const auto xml = juce::AudioProcessor::getXmlFromBinary (state.getData(), size);
        if (xml == nullptr || ! xml->hasTagName (proc.apvts.state.getType()))
        {
            showError ("This file does not contain a mOog preset.");
            return;
        }

        proc.setStateInformation (state.getData(), size);
    }

    presetBox.setText ("User: " + file.getFileNameWithoutExtension(), juce::dontSendNotification);
}

void BassSynthEditor::addControl (const bsyn::spec::Param& d, bool small)
{
    Control k;
    k.id = d.id; k.label = utf8 (d.label); k.small = small;
    if (k.id == "osc3Ctl") k.label = "Osc. 3 Control";
    const bool rockerChoice = (k.id == "extSrc" || k.id == "mode") && d.kind == bsyn::spec::Kind::Choice
                           && d.min == 0.0f && d.max == 1.0f;
    if (d.kind == bsyn::spec::Kind::Bool || rockerChoice)
    {
        k.button = std::make_unique<AnimatedRocker>();
        k.button->setComponentID (d.id);
        k.button->setTitle (utf8 (d.name));
        k.button->setTooltip (tipFor (d.id));
        k.buttonAttachment = std::make_unique<juce::AudioProcessorValueTreeState::ButtonAttachment> (proc.apvts, d.id, *k.button);
        panel.addAndMakeVisible (*k.button);
    }
    else
    {
        k.slider = std::make_unique<juce::Slider> (juce::Slider::RotaryVerticalDrag, juce::Slider::TextBoxBelow);
        k.slider->setComponentID (d.id);
        k.slider->setTitle (utf8 (d.name));
        const auto pi = juce::MathConstants<float>::pi;
        if (d.kind == bsyn::spec::Kind::Choice && (k.id.endsWith ("Range") || k.id.endsWith ("Wave")))
        {
            const bool withoutLo = k.id.endsWith ("Range") && d.choices != nullptr
                                && ! juce::String (d.choices).startsWith ("LO|");
            k.slider->setRotaryParameters (pi * (withoutLo ? 1.7f : 1.5f), pi * 2.5f, true);
        }
        else if (const float mainEnd = printedScaleEnd (d); mainEnd < 1.0f)
        {
            const float start = pi * 4.0f / 3.0f;
            const float fullArc = juce::jmin (pi * 4.0f / (3.0f * mainEnd), pi * 11.0f / 6.0f);
            k.slider->setRotaryParameters (start, start + fullArc, true);
        }
        else
            k.slider->setRotaryParameters (pi * 1.25f, pi * 2.75f, true);
        const int valueWidth = k.id == "cutoff" ? 96 : (small ? 74 : 84);
        k.slider->setTextBoxStyle (juce::Slider::TextBoxBelow, false, valueWidth, 15);
        k.slider->setMouseDragSensitivity (small ? 160 : 200);
        // hold Ctrl (Cmd on Mac) while dragging for fine adjustment (detuning Frequency by cents)
        k.slider->setVelocityModeParameters (0.4, 1, 0.02, true, juce::ModifierKeys::ctrlAltCommandModifiers);
        k.sliderAttachment = std::make_unique<juce::AudioProcessorValueTreeState::SliderAttachment> (proc.apvts, d.id, *k.slider);
        if (auto* prm = proc.apvts.getParameter (d.id))
            k.slider->setDoubleClickReturnValue (true, (double) prm->convertFrom0to1 (prm->getDefaultValue()));
        k.slider->setTooltip (tipFor (d.id));
        panel.addAndMakeVisible (*k.slider);
    }
    controls.push_back (std::move (k));
}

void BassSynthEditor::resized()
{
    if (getLocalBounds().isEmpty() || panel.getLocalBounds().isEmpty())
        return;

    const float scale = juce::jmin ((float) getWidth() / panel.getWidth(), (float) getHeight() / panel.getHeight());
    panel.setTransform (juce::AffineTransform::scale (scale)
                            .translated ((getWidth() - panel.getWidth() * scale) * 0.5f,
                                         (getHeight() - panel.getHeight() * scale) * 0.5f));
}

void BassSynthEditor::layoutPanel()
{
    panelArea = { cheekW, panelTop, panel.getWidth() - 2 * cheekW, panelHeight };
    displayArea = mainPanelBounds ({ controllerCentreX - 87, 104, 174, 130 }).translated (0, -6);
    displayArea.setCentre (panelX (controllerCentreX), displayArea.getCentreY());
    const int setupTop = panelArea.getBottom() + setupGap;
    setupArea = { panelX (47), setupTop, panelX (1107) - panelX (47), panel.getHeight() - setupTop - setupGap };
    badgeArea = { panelX (1140), setupTop + 15, 202, 78 };
    presetBox.setBounds (124, 10, 215, 25);
    savePresetButton.setBounds (presetBox.getRight() + 8, presetBox.getY(), 56, presetBox.getHeight());
    loadPresetButton.setBounds (savePresetButton.getRight() + 6, presetBox.getY(), 56, presetBox.getHeight());
    themeButton.setBounds (editorW - 205, presetBox.getY(), 84, presetBox.getHeight());

    const auto place = [] (Control& k, int x, int y, bool compact)
    {
        const int labelWidth = compact ? 94 : 98;
        const auto positionY = [=] (int offset, int height)
        {
            return compact ? y + offset : panelY (y + offset + height / 2) - height / 2;
        };
        int labelOffset = 0;
        if (k.id.endsWith ("Range") || k.id.endsWith ("Wave"))
            labelOffset = -4;
        else if (k.id == "osc2Freq" || k.id == "osc3Freq")
            labelOffset = 3;

        k.labelArea = { x - labelWidth / 2, positionY (labelOffset, 18), labelWidth, 18 };
        if (k.slider)
        {
            const int width = compact ? 74 : 98;
            const bool filterEnvelope = k.id == "fA" || k.id == "fD" || k.id == "fS";
            const int height = compact ? 80 : (filterEnvelope ? 86 : 104);
            const int top = compact ? y + 17 : panelY (y + 17);
            const int bottom = compact ? top + height : panelY (y + 17 + height);
            k.slider->setBounds (x - width / 2, top, width, bottom - top);
            return;
        }

        if (bridgesDivider (k.id))
            k.labelArea = { x - 80, positionY (-2, 23), 74, 23 };

        if (k.id == "noisePink")
            k.button->setBounds (x - 17, positionY (17, 45) - 12, 34, 69);
        else if (k.id == "extSrc")
            k.button->setBounds (x - 43, positionY (16, mixerRockerHeight), 86, mixerRockerHeight + 13);
        else if (k.id == "mode")
            k.button->setBounds (x - 54, positionY (16, mixerRockerHeight), 108, mixerRockerHeight + 13);
        else if (k.id == "comp")
            k.button->setBounds (x - 27, positionY (19, mixerRockerHeight), 54, mixerRockerHeight + 13);
        else if (k.id == "decaySw")
            k.button->setBounds (x - 38, positionY (19, 28), 76, 28);
        else if (mixerOnSwitch (k.id))
            k.button->setBounds (x - 28, positionY (16, mixerRockerHeight), 56, mixerRockerHeight + 13);
        else
            k.button->setBounds (x - 27, positionY (19, 28), 54, 28);
    };

    const auto auxiliaryCount = std::count_if (controls.begin(), controls.end(), [] (const auto& k) { return k.small; });
    const int columns = juce::jlimit (1, auxiliaryColumns, (int) auxiliaryCount);
    const int step = setupArea.getWidth() / columns;
    int auxiliaryIndex = 0;
    for (auto& k : controls)
    {
        if (const auto* slot = findPlacement (k.id))
            place (k, panelX (slot->x), slot->y, false);
        else
        {
            const int row = auxiliaryIndex / columns;
            const int column = auxiliaryIndex % columns;
            place (k, setupArea.getX() + step / 2 + column * step,
                   setupArea.getY() + 10 + row * auxiliaryRowHeight, true);
            ++auxiliaryIndex;
        }
    }

    const auto findControl = [this] (const char* id)
    {
        return std::find_if (controls.begin(), controls.end(), [id] (const auto& k) { return k.id == id; });
    };
    for (const auto& channel : mixerChannels)
    {
        const auto knob = findControl (channel.level);
        const auto toggle = findControl (channel.toggle);
        if (knob == controls.end() || knob->slider == nullptr
            || toggle == controls.end() || toggle->button == nullptr)
            continue;

        const auto centre = lnf.getSliderLayout (*knob->slider).sliderBounds.getCentre() + knob->slider->getPosition();
        auto& button = *toggle->button;
        button.setTopLeftPosition (button.getX(), centre.y - mixerRockerHeight / 2);
        const float direction = centre.x < button.getBounds().getCentreX() ? 1.0f : -1.0f;
        const float y = (float) centre.y - 2.0f;
        mixerLinks.emplace_back ((float) centre.x + direction * 47.0f, y,
                                 (float) button.getBounds().getCentreX() - direction * 26.0f, y);
    }
}

void BassSynthEditor::paint (juce::Graphics& g)
{
    g.fillAll (juce::Colour (0xff252526));
}

void BassSynthEditor::paintPanel (juce::Graphics& g)
{
    const bool ivory = lnf.isIvory();
    const auto ink = lnf.ink();
    const auto rule = ivory ? colour (0xffa5907b) : colour (panelRule);
    const auto& textures = finishes (ivory);
    juce::Graphics::ScopedSaveState cabinet (g);
    g.reduceClipRegion (softRectangle (panel.getLocalBounds().toFloat().reduced (1.0f), 28.0f));

    auto rail = panel.getLocalBounds();
    const auto left = rail.removeFromLeft (cheekW), right = rail.removeFromRight (cheekW);
    const auto header = rail.removeFromTop (panelArea.getY()).toFloat();
    g.setColour (juce::Colours::white);
    g.drawImage (textures.sideWood, left.toFloat());
    g.drawImageTransformed (textures.sideWood,
                           juce::AffineTransform::scale (-(float) right.getWidth() / textures.sideWood.getWidth(),
                                                          (float) right.getHeight() / textures.sideWood.getHeight())
                               .translated ((float) right.getRight(), (float) right.getY()));
    {
        juce::Graphics::ScopedSaveState saved (g);
        g.reduceClipRegion (header.toNearestInt());
        const float width = (float) textures.header.getWidth();
        const float height = header.getHeight() / (float) textures.header.getHeight();
        for (int i = 0; (float) i * width < header.getWidth(); ++i)
        {
            const bool mirrored = i % 2 != 0;
            const float x = header.getX() + ((float) i + (mirrored ? 1.0f : 0.0f)) * width;
            g.drawImageTransformed (textures.header, juce::AffineTransform::scale (mirrored ? -1.0f : 1.0f, height)
                                                           .translated (x, header.getY()));
        }
    }
    for (const float x : { 0.052f, 0.5f, 0.949f })
    {
        constexpr float size = 16.0f;
        g.drawImage (textures.bolt, { header.getX() + header.getWidth() * x - size * 0.5f, 29.0f, size, size });
    }
    // Fill the cabinet behind the faceplate so the curved corners reveal wood.
    drawLowerWood (g, rail.withY (juce::roundToInt (header.getBottom())).withBottom (panel.getHeight()), textures.lowerWood);
    const auto insetBounds = panelArea.toFloat();
    const auto inset = softRectangle (insetBounds, 20.0f);
    g.setColour (juce::Colours::black.withAlpha (0.35f));
    g.fillPath (softRectangle (insetBounds.expanded (1.8f).translated (0.0f, 1.0f), 22.0f));
    {
        juce::Graphics::ScopedSaveState saved (g);
        g.reduceClipRegion (inset);
        drawSurface (g, panelArea, ivory);
        g.setColour (juce::Colours::black.withAlpha (ivory ? 0.30f : 0.52f));
        g.strokePath (inset, juce::PathStrokeType (3.0f));
    }

    g.setColour (ivory ? colour (0xff53493f) : colour (0xffe2e0dc));
    constexpr int dividerWidth = 2;
    for (const int x : { controllerDivider, oscillatorDivider, modifierDivider, outputDivider })
        g.fillRect (panelX (x) - dividerWidth / 2, panelArea.getY() + 5, dividerWidth, panelArea.getHeight() - 14);
    g.fillRect (panelX (modifierDivider), panelY (envelopeDivider) - dividerWidth / 2,
                panelX (outputDivider) - panelX (modifierDivider), dividerWidth);

    g.setColour (colour (0xff322c26));
    g.setFont (panelFont (11.0f));
    g.drawText ("PRESET", juce::Rectangle<int> { 44, 10, 49, 25 }, juce::Justification::centredLeft);

    struct Caption { const char* text; juce::Rectangle<int> area; };
    const Caption captions[] {
        { "CONTROLLERS", { controllerPanelLeft, 481, controllerDivider - controllerPanelLeft, 33 } },
        { "OSCILLATOR BANK", { controllerDivider, 481, oscillatorDivider - controllerDivider, 33 } },
        { "MIXER", { 594, 481, 330, 33 } }, { "FILTER CONTOUR", { 924, 66, 334, 22 } },
        { "LOUDNESS CONTOUR", { 924, 322, 334, 26 } }, { "OUTPUT", { 1258, 481, 112, 33 } }
    };
    g.setFont (panelFont (28.0f));
    for (const auto& caption : captions)
    {
        const auto bounds = mainPanelBounds (caption.area).reduced (4, 0);
        if (! drawMockupLabel (g, caption.text, bounds, ink))
        {
            g.setColour (ink);
            g.drawFittedText (caption.text, bounds, juce::Justification::centred, 1);
        }
    }
    for (int i = 0; i < 3; ++i)
        drawMockupLabel (g, "oscillator" + juce::String (i + 1),
                         mainPanelBounds ({ oscillatorFrequencyX - 100, oscillatorRow (i) - 17, 200, 19 }), ink);

    const auto setupShape = softRectangle (setupArea.toFloat(), 14.0f);
    {
        juce::Graphics::ScopedSaveState saved (g);
        g.reduceClipRegion (setupShape);
        drawSurface (g, setupArea, ivory);
    }
    g.setColour (rule.withAlpha (0.75f));
    g.strokePath (setupShape, juce::PathStrokeType (1.0f));
    if (ivory)
        for (const auto corner : { setupArea.getTopLeft(), setupArea.getTopRight(),
                                   setupArea.getBottomLeft(), setupArea.getBottomRight() })
            drawScrew (g, (float) (corner.x < setupArea.getCentreX() ? corner.x + 8 : corner.x - 8),
                          (float) (corner.y < setupArea.getCentreY() ? corner.y + 8 : corner.y - 8));

    const auto badge = softRectangle (badgeArea.toFloat(), 13.0f);
    g.setColour (ivory ? colour (0xfff4e0cd) : colour (badgeColour));
    g.fillPath (badge);
    g.setColour (juce::Colours::black.withAlpha (0.35f));
    g.strokePath (badge, juce::PathStrokeType (1.0f));
    g.setColour (ink);
    const auto wordmark = badgeArea.withSizeKeepingCentre (132, 42).withY (badgeArea.getCentreY() - 24);
    g.setFont (panelFont (46.0f));
    g.drawFittedText ("mOog", wordmark, juce::Justification::centred, 1);
    g.setFont (panelFont (10.0f, true, 0.19f));
    g.drawText ("DI TO SYNTH", badgeArea.withY (wordmark.getBottom() - 7).withHeight (14),
                juce::Justification::centred);

    g.setColour (ink.withAlpha (0.75f));
    for (const auto& link : mixerLinks)
        g.drawLine (link, 1.2f);

    for (const auto& k : controls)
    {
        if (mixerOnSwitch (k.id) || k.id == "noisePink")
            continue;
        const auto text = k.label.toUpperCase();
        const auto key = k.id == "fD" || k.id == "aD" ? juce::String ("decayTime") : (k.id == "outGain" ? k.id : text);
        if (! k.small && drawMockupLabel (g, key, k.labelArea, ink))
            continue;
        g.setColour (ink);
        const bool compactLabel = k.small || k.button != nullptr;
        const float labelSize = compactLabel ? 13.0f : 16.0f;
        g.setFont (panelFont (labelSize));
        g.drawFittedText (text, k.labelArea, juce::Justification::centred, 2, 0.78f);
    }

    auto window = displayArea.toFloat();
    const auto lamps = window.removeFromTop (23.0f);
    window.removeFromBottom (4.0f);

    const auto status = [&g, lamps, ink] (const char* label, float centreX, bool active, juce::Colour lit)
    {
        const juce::Rectangle<float> lens (centreX - 16.0f, lamps.getCentreY() - 3.0f, 6.0f, 6.0f);
        g.setColour (juce::Colour (0xff13100e));
        g.fillEllipse (lens.expanded (1.3f));
        if (active)
        {
            g.setColour (lit.withAlpha (0.21f));
            g.fillEllipse (lens.expanded (2.0f));
        }
        g.setColour (active ? lit : C::pilotOff);
        g.fillEllipse (lens);
        g.setColour (ink);
        g.setFont (panelFont (10.5f, true, 0.3f));
        g.drawText (label, juce::Rectangle<float> { centreX - 5.0f, lamps.getY(), 37.0f, lamps.getHeight() },
                    juce::Justification::centredLeft);
    };
    status ("TRIG", lamps.getX() + lamps.getWidth() * 0.30f, trigFlash > 0, C::amber);
    status ("GATE", lamps.getX() + lamps.getWidth() * 0.70f, gateLed, juce::Colour (0xffff593d));

    g.setGradientFill (juce::ColourGradient (juce::Colour (0xff100c09), window.getTopLeft(),
                                             juce::Colour (0xff22120b), window.getBottomLeft(), false));
    const auto screen = softRectangle (window, 9.0f);
    g.fillPath (screen);
    g.setColour (juce::Colour (0xff504032).withAlpha (0.75f));
    g.strokePath (screen, juce::PathStrokeType (0.9f));

    auto content = window.reduced (10.0f, 9.0f);
    const auto pitch = content.removeFromLeft (content.getWidth() * 0.49f).reduced (4.0f, 0.0f);
    juce::String note = "--";
    juce::String hertz = "--.-";
    if (std::isfinite (freq) && freq > 0.0f)
    {
        static const char* names[] { "C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B" };
        const int midi = (int) std::lround (69.0 + 12.0 * std::log2 ((double) freq / 440.0));
        const int pitchClass = ((midi % 12) + 12) % 12;
        note = juce::String (names[pitchClass]) + juce::String ((midi - pitchClass) / 12 - 1);
        hertz = juce::String (freq, 1);
    }
    drawSegmentDisplay (g, note, pitch.withY (pitch.getY() + 9.0f).withHeight (36.0f));
    auto frequency = pitch.withY (pitch.getY() + 54.0f).withHeight (15.0f);
    const auto unit = frequency.removeFromRight (15.0f);
    drawSegmentDisplay (g, hertz, frequency);
    g.setColour (C::silkDim);
    g.setFont (panelFont (9.0f));
    g.drawText ("Hz", unit, juce::Justification::centredRight);

    const auto meter = [&g] (juce::Rectangle<float> lane, const char* label, float level)
    {
        constexpr int cells = 7;
        const auto caption = lane.removeFromBottom (13.0f);
        const float step = lane.getHeight() / (float) cells;
        const int litCount = juce::roundToInt (juce::jlimit (0.0f, 1.0f, level) * (float) cells);
        for (int i = 0; i < cells; ++i)
        {
            const float y = lane.getBottom() - (float) (i + 1) * step + 1.0f;
            const juce::Rectangle<float> cell (lane.getCentreX() - 6.0f, y, 12.0f, step - 2.6f);
            if (i < litCount)
            {
                const auto lit = i >= cells - 2 ? juce::Colour (0xffff8a39) : juce::Colour (0xffefac42);
                g.setColour (lit.withAlpha (0.16f));
                g.fillRect (cell.expanded (0.9f));
                g.setColour (lit);
            }
            else
                g.setColour (juce::Colour (0xff382116));
            g.fillRoundedRectangle (cell, 0.6f);
        }
        g.setColour (C::silk);
        g.setFont (panelFont (9.0f));
        g.drawFittedText (label, caption.toNearestInt(), juce::Justification::centred, 1, 0.8f);
    };
    const auto laneWidth = content.getWidth() / 3.0f;
    meter (content.removeFromLeft (laneWidth), "INPUT", input);
    meter (content.removeFromLeft (laneWidth), "FILTER", filterEnv);
    meter (content, "AMP", ampEnv);
}

void BassSynthEditor::timerCallback()
{
    const uint32_t t = proc.displayTrig.load();
    if (t != lastTrig) { lastTrig = t; trigFlash = 3; }
    else if (trigFlash > 0) --trigFlash;
    gateLed = proc.displayGate.load();
    freq = proc.displayFreq.load();
    input = proc.displayInput.load();
    filterEnv = proc.displayFilterEnv.load();
    ampEnv = proc.displayAmpEnv.load();
    panel.repaint (displayArea);
}

